/*
  SJSU E10 / VEX Cortex beacon robot -- full autonomous run (Tasks 1-4)

  What it does:
    1. Finds the red (1 kHz) beacon and stops when the front switch touches it.
    2. Presses the red beacon's top button with the press arm until it is off.
    3. Backs away, then finds the green (10 kHz) beacon.
    4. Presses the arm down on the green beacon, closes the claw, and backs up
       past the starting point, pulling the green beacon across the line.

  Wiring:
    - IR receiver board: ribbon cable in digital 9-12 (uses 10, 11, 12),
      3-wire cable in analog 1
    - Front limit switch: digital 3
    - Right drive motor: motor port 1      - Left drive motor: motor port 10
    - Claw servo: motor port 2             - Press arm servo: motor port 3
    - No bumper and no ultrasonic sensor.

  How to run:
    1. Charge the battery fully and push every cable in firmly.
    2. Download this program and put the robot behind the starting line,
       facing into the arena.
    3. Press and release the front switch. The robot starts 1 second later.
    4. With the robot connected, Robot > Debugger Windows > Debug Stream shows
       each step, the time it happened, and the sensor values to tune.

  Before the first full run, tune the values in the CALIBRATION section below.

  Notes:
    - The drive motors use the same output equations as the working GoToBeacon
      code. Negative speed values make this robot drive forward.
    - Position tracking is open-loop dead reckoning from commanded motor power and
      elapsed time. It is NOT encoder odometry and will drift with battery level,
      wheel slip, floor friction, and turns.
*/

