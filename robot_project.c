int ExposeAndRead()
{
    int intensity;

    SensorValue[digital11] = 1;    // Close shutter and advance detector counter.
    wait1Msec(5);
    SensorValue[digital11] = 0;    // Open shutter.
    wait1Msec(expose_time);
    intensity = SensorValue[analog1];

    return intensity;
}

void ReadPD()
{
    SensorValue[digital11] = 1;    // Close shutter.
    SensorValue[digital12] = 1;    // Reset selector to photodiode 0.
    SensorValue[digital12] = 0;    // Enable automatic selector advance.
    wait1Msec(5);

    SensorValue[digital11] = 0;    // Open shutter.
    wait1Msec(expose_time);

    PD0 = SensorValue[analog1];
    PD1 = ExposeAndRead();
    PD2 = ExposeAndRead();
    PD3 = ExposeAndRead();
    PD4 = ExposeAndRead();
    PD5 = ExposeAndRead();
    PD6 = ExposeAndRead();
    PD7 = ExposeAndRead();

    PD_sum = PD0 + PD1 + PD2 + PD3 + PD4 + PD5 + PD6 + PD7;
}

void FindMax()
{
    max_val = PD0;
    max_no = 0;

    if(PD1 > max_val) { max_val = PD1; max_no = 1; }
    if(PD2 > max_val) { max_val = PD2; max_no = 2; }
    if(PD3 > max_val) { max_val = PD3; max_no = 3; }
    if(PD4 > max_val) { max_val = PD4; max_no = 4; }
    if(PD5 > max_val) { max_val = PD5; max_no = 5; }
    if(PD6 > max_val) { max_val = PD6; max_no = 6; }
    if(PD7 > max_val) { max_val = PD7; max_no = 7; }
}

void FollowBeacon()
{
    int error;
    int steer;
    int speed;

    error = 4 - max_no;             // PD4 is the center detector.
    steer = error * STEER_SENSITIVITY;
    speed = FORWARD_SPEED;          // Negative is forward on this robot.

    if(PD_sum < AMBIENT_LEVEL)
    {
        speed = 0;
        steer = -SEARCH_SPIN_SPEED;  // Search in place until the beacon is detected.
    }
    else if(PD_sum > SLOW_LEVEL)
    {
        speed = APPROACH_SLOW_SPEED;
    }

    // Preserve the currently working GoToBeacon motor mixing.
    SetDrive(steer + speed, steer - speed);
}

// -----------------------------------------------------------------------------
// Beacon seeking and verification.
// -----------------------------------------------------------------------------

int LimitSwitchPressed()
{
    return (SensorValue[frontLimit] == LIMIT_PRESSED_LEVEL);
}

void SetFrequency(int targetFrequency)
{
    freq = targetFrequency;
    SensorValue[digital10] = freq;
    wait1Msec(FREQUENCY_SETTLE_MS);
}

// Retreat until the front switch is definitely released. Without this check,
// SeekBeacon(GREEN) could mistake a still-pressed red-beacon switch for contact
// with the green beacon and start the green pickup sequence at the wrong place.
int BackAwayFromRedBeacon()
{
    int elapsedMs;

    DriveStraightFor(-RED_BACKOFF_POWER, RED_BACKOFF_TIME_MS);
    elapsedMs = 0;

    while(LimitSwitchPressed() && elapsedMs < RED_BACKOFF_EXTRA_TIMEOUT_MS)
    {
        DriveStraightFor(-RED_BACKOFF_POWER, BACKOFF_STEP_MS);
        elapsedMs += BACKOFF_STEP_MS;
    }

    wait1Msec(75); // short release/debounce check
    return !LimitSwitchPressed();
}

// Called right after ReadPD() at targetFrequency. A close beacon also shows up on
// the wrong frequency (lab guidelines section 7.4), so read the other beacon's
// frequency too: a detector that reads higher there is looking at the other
// beacon, and its reading is ignored (set to 0). PD_sum is recomputed from the
// readings that are left, so the robot steers only toward the right beacon.
void IgnoreOtherBeacon(int targetFrequency)
{
    int t0, t1, t2, t3, t4, t5, t6, t7;

    t0 = PD0; t1 = PD1; t2 = PD2; t3 = PD3;
    t4 = PD4; t5 = PD5; t6 = PD6; t7 = PD7;

    SensorValue[digital10] = 1 - targetFrequency;
    wait1Msec(CROSSTALK_SETTLE_MS);
    ReadPD();                       // PD0..PD7 now hold the other frequency

    SensorValue[digital10] = targetFrequency;
    wait1Msec(CROSSTALK_SETTLE_MS);

    if(PD0 > t0) t0 = 0;
    if(PD1 > t1) t1 = 0;
    if(PD2 > t2) t2 = 0;
    if(PD3 > t3) t3 = 0;
    if(PD4 > t4) t4 = 0;
    if(PD5 > t5) t5 = 0;
    if(PD6 > t6) t6 = 0;
    if(PD7 > t7) t7 = 0;

    PD0 = t0; PD1 = t1; PD2 = t2; PD3 = t3;
    PD4 = t4; PD5 = t5; PD6 = t6; PD7 = t7;
    PD_sum = PD0 + PD1 + PD2 + PD3 + PD4 + PD5 + PD6 + PD7;
}

// Called when the front switch touches a beacon. Close up, the normal readings
// can max out on both frequencies, so read both again with a short exposure.
// Returns 1 if the target frequency reads at least as strong (right beacon),
// 0 if the other frequency is stronger (the other beacon is in the way).
int TouchingTargetBeacon(int targetFrequency)
{
    int targetSum;
    int otherSum;

    expose_time = TOUCH_CHECK_EXPOSURE_MS;

    ReadPD();
    targetSum = PD_sum;

    SensorValue[digital10] = 1 - targetFrequency;
    wait1Msec(FREQUENCY_SETTLE_MS);
    ReadPD();
    otherSum = PD_sum;

    SensorValue[digital10] = targetFrequency;
    wait1Msec(FREQUENCY_SETTLE_MS);

    expose_time = EXPOSURE_TIME_MS;
    return (targetSum >= otherSum);
}

// Drive to the beacon until the front switch is pressed. A press with a weak
// beacon reading is a wall: back up, turn a little, and keep searching. A press
// on the other beacon: go around it. checkOtherBeacon = 1 ignores readings that
// come from the other beacon (slower: each reading is taken on both frequencies).
int SeekBeacon(int targetFrequency, long timeoutMs, int checkOtherBeacon)
{
    long startTime;
    int rawSum;
    int t;

    StopDrive();
    SetFrequency(targetFrequency);

    startTime = nSysTime;

    while((nSysTime - startTime) < timeoutMs)
    {
        ReadPD();
        rawSum = PD_sum;

        if(checkOtherBeacon && PD_sum >= AMBIENT_LEVEL)
            IgnoreOtherBeacon(targetFrequency);

        if(LimitSwitchPressed())
        {
            StopDrive();
            t = RunTenths();

            if(rawSum < TOUCH_SIGNAL_LEVEL)
            {
                writeDebugStreamLine("%d.%d s  wall? PD_sum=%d: back off", t / 10, t % 10, rawSum);
                DriveStraightFor(-RED_BACKOFF_POWER, WALL_BACKOFF_TIME_MS);
                SpinFor(WALL_TURN_TIME_MS);
                continue;
            }

            if(targetFrequency == GREEN_BEACON_FREQUENCY && redSpotKnown &&
               DistanceFromRedSpot() < RED_SPOT_RADIUS_CM)
            {
                writeDebugStreamLine("%d.%d s  red beacon in the way: go around", t / 10, t % 10);
                GoAround();
                continue;
            }

            if(!checkOtherBeacon || TouchingTargetBeacon(targetFrequency))
            {
                writeDebugStreamLine("%d.%d s  touched beacon, PD_sum=%d", t / 10, t % 10, rawSum);
                return 1;
            }

            writeDebugStreamLine("%d.%d s  other beacon in the way: go around", t / 10, t % 10);
            GoAround();
            continue;
        }

        FindMax();
        FollowBeacon();
        wait1Msec(10);
    }

    StopDrive();
    return 0;
}

// The red beacon is considered OFF only after several consecutive low readings.
// The board can still pick up a nearby green beacon while tuned to red
// (lab guidelines section 7.4), so if the red reading stays high, read at the
// green frequency too: a stronger green reading means the "red" signal is really
// green crosstalk and the red beacon is off.
int VerifyRedOff()
{
    int sample;
    int clearReadings;
    long redTotal;
    int redAverage;
    int greenSum;

    StopDrive();
    SetFrequency(RED_BEACON_FREQUENCY);

    clearReadings = 0;
    redTotal = 0;

    for(sample = 0; sample < VERIFY_SAMPLE_COUNT; sample++)
    {
        ReadPD();
        redTotal += PD_sum;

        if(PD_sum < AMBIENT_LEVEL)
            clearReadings++;
        else
            clearReadings = 0;

        wait1Msec(60);
    }

    if(clearReadings >= VERIFY_REQUIRED_CLEAR)
    {
        writeDebugStreamLine("  red check: OFF");
        return 1;
    }

    redAverage = redTotal / VERIFY_SAMPLE_COUNT;

    SetFrequency(GREEN_BEACON_FREQUENCY);
    ReadPD();
    greenSum = PD_sum;
    SetFrequency(RED_BEACON_FREQUENCY);

    if(greenSum >= redAverage)
    {
        writeDebugStreamLine("  red check: OFF (red=%d green=%d)", redAverage, greenSum);
        return 1;
    }

    writeDebugStreamLine("  red check: still ON (red=%d green=%d)", redAverage, greenSum);
    return 0;
}

int PressRedUntilOff()
{
    int attempt;

    for(attempt = 0; attempt < MAX_BUTTON_ATTEMPTS; attempt++)
    {
        writeDebugStreamLine("  press %d", attempt + 1);
        motor[pressArmServo] = PRESS_ARM_BUTTON_POS;
        wait1Msec(BUTTON_PRESS_TIME_MS);

        motor[pressArmServo] = PRESS_ARM_HOME_POS;
        wait1Msec(SERVO_MOVE_TIME_MS);

        if(VerifyRedOff())
            return 1;
    }

    return 0;
}

// -----------------------------------------------------------------------------
// Return to the start while moving backward and keeping the claw closed.
// The desired chassis heading is opposite the homeward travel direction because
// the robot is pulling the beacon behind itself. The target is
// RETURN_PAST_START_CM behind the starting point, because the beacon is held in
// front of the robot and has to end up past the starting line.
// -----------------------------------------------------------------------------

int ReturnToStartBackward()
{
    long startTime;
    float dx;
    float dy;
    float distanceToHome;
    float homeBearing;
    float desiredRobotHeading;
    float headingError;
    float steerFloat;
    int steer;
    int rightPower;
    int leftPower;

    startTime = nSysTime;

    UpdateOdometry();
    writeDebugStreamLine("  position estimate: x=%d y=%d cm", (int)robotX, (int)robotY);

    while((nSysTime - startTime) < RETURN_TIMEOUT_MS)
    {
        UpdateOdometry();

        dx = -robotX;
        dy = -RETURN_PAST_START_CM - robotY;
        distanceToHome = sqrt((dx * dx) + (dy * dy));

        if(distanceToHome <= HOME_TOLERANCE_CM &&
           (nSysTime - startTime) >= RETURN_MIN_TIME_MS)
        {
            StopDrive();
            writeDebugStreamLine("  reached the start (estimate)");
            return 1;
        }

        // Bearing from current estimated position to the origin, measured
        // clockwise from the original forward direction.
        homeBearing = Atan2Compat(dx, dy);

        // Because the robot is backing up while towing the beacon, its nose
        // points in the opposite direction from the desired travel direction.
        desiredRobotHeading = NormalizeAngle(homeBearing + PI_VALUE);
        headingError = NormalizeAngle(desiredRobotHeading - robotHeading);

        steerFloat = headingError * RETURN_STEER_GAIN;
        if(steerFloat > RETURN_MAX_STEER) steerFloat = RETURN_MAX_STEER;
        if(steerFloat < -RETURN_MAX_STEER) steerFloat = -RETURN_MAX_STEER;
        steer = (int)steerFloat;

        // Positive speed is physical reverse for this robot's tested motor mix.
        rightPower = LimitPWM(steer + RETURN_BACKWARD_POWER);
        leftPower = LimitPWM(steer - RETURN_BACKWARD_POWER);
        SetDrive(rightPower, leftPower);

        wait1Msec(40);
    }

    StopDrive();
    writeDebugStreamLine("  return timed out");
    return 0;
}

void StopAndHold()
{
    StopDrive();
    // Keep the servos at their current positions; do not release the beacon.
    while(true)
        wait1Msec(100);
}

