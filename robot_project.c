#define MAX_WHEEL_SPEED_CM_PER_SEC  40.0   // test 1
#define TRACK_WIDTH_CM              25.0   // test 2 (an "effective" width from a spin)
#define PULL_SPEED_FACTOR           0.85   // test 3: speed while pulling the green beacon
#define RETURN_BACKWARD_POWER        45   // lower if the beacon slips out while pulling
#define RETURN_STEER_GAIN            45.0
#define RETURN_MAX_STEER             45
#define HOME_TOLERANCE_CM            15.0
#define RETURN_PAST_START_CM         80.0   // stop this far behind where the robot started:
