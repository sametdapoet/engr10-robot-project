// -----------------------------------------------------------------------------
// Hardware and calibration settings -- adjust these for your robot.
// -----------------------------------------------------------------------------

// Touch switch is normally 1 when pressed. Change to 0 if your switch is wired
// as an active-low input.
#define LIMIT_PRESSED_LEVEL       1

// Servo command range for these VEX servo modules is -127 to +127.
// These are STARTING VALUES ONLY. Use the servo test procedure in the notes
// accompanying this program to calibrate the positions without straining linkages.
#define CLAW_OPEN_POS            -80
#define CLAW_CLOSED_POS           60
#define PRESS_ARM_HOME_POS       -80
#define PRESS_ARM_BUTTON_POS      60
#define PRESS_ARM_HOLD_GREEN_POS   60   // Arm pressed down on top of the green beacon to pin it
                                       // while pulling. Start at the button value; raise it if
                                       // the arm crushes the beacon, lower it if the beacon slips.

#define SERVO_MOVE_TIME_MS       650
#define BUTTON_PRESS_TIME_MS     500

// IR board settings from the GoToBeacon program / SJSU lab description.
#define RED_BEACON_FREQUENCY       0   // 0 = 1 kHz
#define GREEN_BEACON_FREQUENCY     1   // 1 = 10 kHz
#define EXPOSURE_TIME_MS           5
#define AMBIENT_LEVEL            200
#define SLOW_LEVEL              5000

// When the front switch is pressed, the beacon reading must be at least this
// strong to count as touching the beacon. A weaker reading means the robot ran
// into a wall. Check the PD_sum value at contact on the real robot and tune.
#define TOUCH_SIGNAL_LEVEL      2000

// Keep the signs and steering equation consistent with the robot's working test.
// With this robot, negative speed values command physical forward movement.
#define FORWARD_SPEED            -35
#define APPROACH_SLOW_SPEED      -25
#define SEARCH_SPIN_SPEED         50
#define STEER_SENSITIVITY         20

// Timeouts and movement durations. Tune on the real arena at low speed first.
#define RED_SEARCH_TIMEOUT_MS  90000
#define GREEN_SEARCH_TIMEOUT_MS 90000
#define MAX_BUTTON_ATTEMPTS        4
#define VERIFY_SAMPLE_COUNT        6
#define VERIFY_REQUIRED_CLEAR      4
#define FREQUENCY_SETTLE_MS      150
#define CROSSTALK_SETTLE_MS       30   // quick frequency switch for the wrong-beacon check

#define RED_BACKOFF_POWER          35   // positive here means physically backward
#define RED_BACKOFF_TIME_MS      650
#define RED_BACKOFF_EXTRA_TIMEOUT_MS 1500
#define BACKOFF_STEP_MS            100

#define WALL_BACKOFF_TIME_MS     500
#define WALL_TURN_TIME_MS        400

// Dead-reckoning calibration:
// Measure the robot's straight-line distance at full command for 1 second.
// Set MAX_WHEEL_SPEED_CM_PER_SEC to that distance in centimeters.
// Measure TRACK_WIDTH_CM between the left and right wheel contact centerlines.
#define MAX_WHEEL_SPEED_CM_PER_SEC  40.0
#define TRACK_WIDTH_CM              25.0
#define RETURN_BACKWARD_POWER        30
#define RETURN_STEER_GAIN            45.0
#define RETURN_MAX_STEER             45
#define HOME_TOLERANCE_CM            15.0
#define RETURN_TIMEOUT_MS         45000
#define RETURN_MIN_TIME_MS         1500   // always back up at least this long, even if the
                                         // position estimate already says "home"
#define MAX_ODOMETRY_STEP_MS        250

#define PI_VALUE 3.14159265

// -----------------------------------------------------------------------------
// IR receiver board state (preserved from the original GoToBeacon program).
// -----------------------------------------------------------------------------

int freq;
int expose_time;
int PD0, PD1, PD2, PD3, PD4, PD5, PD6, PD7;
int PD_sum;
int max_val;
int max_no;

// -----------------------------------------------------------------------------
// Open-loop odometry state.
// Coordinate convention: x is to the robot's initial right, y is forward,
// and heading 0 means the robot initially faces into the arena.
// -----------------------------------------------------------------------------

float robotX = 0.0;
float robotY = 0.0;
float robotHeading = 0.0;
long lastOdometryTime = 0;
int lastRightCommand = 0;
int lastLeftCommand = 0;

// The tested straight-ahead command pair is right=-power, left=+power.
// These signs convert motor output values into estimated physical wheel speed.
#define RIGHT_FORWARD_SIGN -1.0
#define LEFT_FORWARD_SIGN   1.0

// -----------------------------------------------------------------------------
// Small utility functions.
// -----------------------------------------------------------------------------

void UpdateOdometry();

int LimitPWM(int value)
{
    if(value > 127) return 127;
    if(value < -127) return -127;
    return value;
}

float NormalizeAngle(float angle)
{
    while(angle > PI_VALUE) angle -= 2.0 * PI_VALUE;
    while(angle < -PI_VALUE) angle += 2.0 * PI_VALUE;
    return angle;
}

// ROBOTC provides atan(), but some versions do not provide atan2().
// This helper returns atan2(y, x) with the correct quadrant.
float Atan2Compat(float y, float x)
{
    if(x > 0.0) return atan(y / x);
    if(x < 0.0 && y >= 0.0) return atan(y / x) + PI_VALUE;
    if(x < 0.0 && y < 0.0) return atan(y / x) - PI_VALUE;
    if(x == 0.0 && y > 0.0) return PI_VALUE / 2.0;
    if(x == 0.0 && y < 0.0) return -PI_VALUE / 2.0;
    return 0.0;
}

void StopDrive()
{
    // SetDrive() accounts for the movement that occurred before stopping.
    UpdateOdometry();
    motor[rightMotor] = 0;
    motor[leftMotor] = 0;
    lastRightCommand = 0;
    lastLeftCommand = 0;
}

// -----------------------------------------------------------------------------
// Encoderless dead reckoning.
// Call this immediately before changing the drive outputs so the elapsed time
// is attributed to the commands that were active during that interval.
// -----------------------------------------------------------------------------

void UpdateOdometry()
{
    long now;
    long elapsedMs;
    float dt;
    float leftForwardPwm;
    float rightForwardPwm;
    float leftVelocity;
    float rightVelocity;
    float linearVelocity;
    float angularVelocity;
    float deltaHeading;
    float middleHeading;
    float distance;

    now = nSysTime;
    elapsedMs = now - lastOdometryTime;
    lastOdometryTime = now;

    if(elapsedMs <= 0) return;
    if(elapsedMs > MAX_ODOMETRY_STEP_MS)
        elapsedMs = MAX_ODOMETRY_STEP_MS;

    dt = (float)elapsedMs / 1000.0;

    leftForwardPwm = LEFT_FORWARD_SIGN * (float)lastLeftCommand;
    rightForwardPwm = RIGHT_FORWARD_SIGN * (float)lastRightCommand;

    leftVelocity = (leftForwardPwm / 127.0) * MAX_WHEEL_SPEED_CM_PER_SEC;
    rightVelocity = (rightForwardPwm / 127.0) * MAX_WHEEL_SPEED_CM_PER_SEC;

    linearVelocity = (leftVelocity + rightVelocity) / 2.0;
    angularVelocity = (leftVelocity - rightVelocity) / TRACK_WIDTH_CM;

    deltaHeading = angularVelocity * dt;
    middleHeading = robotHeading + (deltaHeading / 2.0);
    distance = linearVelocity * dt;

    // Heading is measured clockwise from the initial forward direction.
    robotX += distance * sin(middleHeading);
    robotY += distance * cos(middleHeading);
    robotHeading = NormalizeAngle(robotHeading + deltaHeading);
}

void SetDrive(int rightPower, int leftPower)
{
    UpdateOdometry();

    lastRightCommand = LimitPWM(rightPower);
    lastLeftCommand = LimitPWM(leftPower);

    motor[rightMotor] = lastRightCommand;
    motor[leftMotor] = lastLeftCommand;
}

// Signed speed: positive = physical forward, negative = physical backward.
// This helper preserves the known straight-drive motor polarity for this robot.
void DriveStraightFor(int signedSpeed, int durationMs)
{
    int remainingMs;
    int stepMs;

    SetDrive(-signedSpeed, signedSpeed);
    remainingMs = durationMs;

    // Update the estimator periodically during long timed moves. If odometry
    // were updated only after a 650 ms move, the maximum-step safeguard would
    // discard part of the travel distance.
    while(remainingMs > 0)
    {
        stepMs = remainingMs;
        if(stepMs > MAX_ODOMETRY_STEP_MS)
            stepMs = MAX_ODOMETRY_STEP_MS;

        wait1Msec(stepMs);
        UpdateOdometry();
        remainingMs -= stepMs;
    }

    StopDrive();
}

// Spin in place in the same direction as the beacon search, for a set time.
void SpinFor(int durationMs)
{
    int remainingMs;
    int stepMs;

    SetDrive(-SEARCH_SPIN_SPEED, -SEARCH_SPIN_SPEED);
    remainingMs = durationMs;

    while(remainingMs > 0)
    {
        stepMs = remainingMs;
        if(stepMs > MAX_ODOMETRY_STEP_MS)
            stepMs = MAX_ODOMETRY_STEP_MS;

        wait1Msec(stepMs);
        UpdateOdometry();
        remainingMs -= stepMs;
    }

    StopDrive();
}

