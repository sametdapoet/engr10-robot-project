/*
ENGR 10 Robot Project - full run (based on the GOTO_BEACON sample)
  Task 1: find the red beacon (1 kHz) and stop at it (front limit switch)
  Task 2: swing the arm (rod on a servo) down onto the beacon's push button to turn it off
  Task 3: find the green beacon (10 kHz)
  Task 4: push the green beacon out of the arena past the starting line

ASSUMED WIRING - change the #pragma lines above if your robot is different:
  dgtl1  = limit switch on the front, pressed when the robot touches a beacon
  dgtl2  = bumper switch (front/side), pressed when the robot hits a wall
  dgtl3  = ultrasonic sensor ("INPUT" cable in dgtl3, "OUTPUT" cable in dgtl4)
  port2  = arm servo (through a Motor Controller 29)
  dgtl10-12 and in1 = IR receiver board, same as the sample program
*/

// Global Variables (same as the sample program)
int freq, ambient_level, slow_level, stop_level, expose_time, steer_sensitivity, forward_speed, slow_speed, spin_speed;
int PD0, PD1, PD2, PD3, PD4, PD5, PD6, PD7, PD_sum;
int max_val, max_no = 0;

// Arm servo tuning - adjust these on the real robot
// Servo position -127..127 covers about -50..+50 degrees. The servo holds whatever position it is given.
int arm_up_pos = 127;       // arm raised, out of the way (swap the two values if the arm moves the wrong way)
int arm_down_pos = -60;     // arm lowered far enough to press the beacon's button
int arm_move_time = 600;    // ms for the servo to reach a new position

// Task 4 tuning
int open_distance = 150;    // cm; a sonar reading farther than this means "open side of the arena"
int push_time = 4000;       // ms to drive forward pushing the green beacon out
int turn_with_beacon_speed = 30; // slower turning so the green beacon doesn't slip out of the scoop

int Expose_and_read(){
	SensorValue[digital11] = 1; // close the shutter, clear the film, and increment the counter
	delay(5); // Wait for 5ms for things to settle
	SensorValue[digital11] = 0; // open shutter for exposure
	delay(expose_time);
	int intensity = SensorValue[analog1]; // get the IR intensity reading
	return intensity;
}

/*Read_PD calculates PD_sum which is the sum of all 8 photo diodes' outputs.
PD_sum is a measure of the distance between the robot and the beacon.*/
void ReadPD(){
	SensorValue[digital11] = 1; // close the shutter, clear the film, and increment the counter
	SensorValue[digital12] = 1; // initialize counter value to '0'
	SensorValue[digital12] = 0; // allow counter to count
	delay(5);
	SensorValue[digital11] = 0; // open shutter and expose film
	delay(expose_time);
	PD0 = SensorValue[analog1];
	PD1 = Expose_and_read();
	PD2 = Expose_and_read();
	PD3 = Expose_and_read();
	PD4 = Expose_and_read();
	PD5 = Expose_and_read();
	PD6 = Expose_and_read();
	PD7 = Expose_and_read();
	PD_sum = PD0 + PD1 + PD2 + PD3 + PD4 + PD5 + PD6 + PD7;
}

/*Stores the largest photo diode reading in max_val and its number in max_no.*/
void Find_max(){
	max_val = PD0;
	max_no = 0;
	if(PD1 > max_val){ max_val = PD1; max_no = 1; }
	if(PD2 > max_val){ max_val = PD2; max_no = 2; }
	if(PD3 > max_val){ max_val = PD3; max_no = 3; }
	if(PD4 > max_val){ max_val = PD4; max_no = 4; }
	if(PD5 > max_val){ max_val = PD5; max_no = 5; }
	if(PD6 > max_val){ max_val = PD6; max_no = 6; }
	if(PD7 > max_val){ max_val = PD7; max_no = 7; }
}

/*Limits results of move function to max speed*/
int limit_pwm(int temp){
	if(temp > 127) return 127;
	if(temp < -127) return -127;
	return temp;
}

/*Same steering as the sample: spin to search, steer toward the brightest diode, slow down when close.*/
void Move(){
	int error = 4 - max_no; // heading direction error, if PD4==max_no, then no error
	int steer = error * steer_sensitivity;
	int speed = forward_speed;

	if(PD_sum < ambient_level){ // beacon not seen - search mode
		speed = 0;
		steer = -spin_speed;
	}
	if(PD_sum > slow_level){ // beacon is near - slow down
		speed = slow_speed;
	}

	motor[rightMotor] = limit_pwm(steer + speed);
	motor[leftMotor] = limit_pwm(steer - speed);
}

// Drive helpers. forward > 0 drives forward, turn > 0 spins the same way as search mode.
void Drive(int forward, int turn){
	motor[rightMotor] = limit_pwm(turn + forward);
	motor[leftMotor] = limit_pwm(turn - forward);
}

void StopDrive(){
	motor[rightMotor] = 0;
	motor[leftMotor] = 0;
}

void SetFrequency(int beacon_freq){
	freq = beacon_freq;
	SensorValue[digital10] = freq; // 0 = 1kHz (red), 1 = 10kHz (green)
	delay(20);
}

/*Tasks 1 and 3: drive to the beacon at the given frequency until the front limit switch is pressed.
If the switch is pressed but the beacon reading is weak, we hit a wall instead - back up, turn, keep looking.*/
void GoToBeacon(int beacon_freq){
	SetFrequency(beacon_freq);

	while(true){
		ReadPD();
		if(SensorValue[frontLimit] == 1){
			if(PD_sum > slow_level) break; // touching the beacon
			Drive(-40, 0);
			delay(500);
			Drive(0, -spin_speed);
			delay(400);
		}
		Find_max();
		Move();
	}
	StopDrive();
	delay(300);
}

/*Checks whether the red beacon is off. Because the board can pick up a nearby green beacon even when
tuned to red (guidelines section 7.4), read at both frequencies: if green reads stronger, the red reading is just
crosstalk from the green beacon and red is actually off.*/
bool RedIsOff(){
	SetFrequency(0);
	ReadPD();
	int red_sum = PD_sum;
	if(red_sum < ambient_level) return true;

	SetFrequency(1);
	ReadPD();
	int green_sum = PD_sum;
	SetFrequency(0);

	return green_sum >= red_sum;
}

/*Task 2: push the red beacon's button with the arm, then check it is off. Tries up to 3 times.*/
void TurnOffRedBeacon(){
	for(int attempt = 0; attempt < 3; attempt++){
		motor[armServo] = arm_down_pos;
		delay(arm_move_time);
		delay(300);             // hold the button down briefly
		motor[armServo] = arm_up_pos;
		delay(arm_move_time);
		delay(200);

		if(RedIsOff()) return;

		// still on - back up a little, creep forward to the switch again and retry
		Drive(-30, 0);
		delay(300);
		StopDrive();
		GoToBeacon(0);
	}
}

/*Task 4: find the open side of the arena with the sonar and push the green beacon out.
Bumper hits mean a wall, so back up, turn and look again.
MECHANICAL NOTE: the robot turns in place here, so the front needs a U-shaped scoop that keeps the beacon
in front while turning, and the sonar must be mounted ABOVE the beacon so it sees over it (otherwise it
only ever sees the beacon a few cm away).*/
void PushGreenOut(){
	while(true){
		// turn slowly until the sonar sees open space (-1 means no echo, i.e. nothing in range)
		clearTimer(T1);
		while(SensorValue[sonar] != -1 && SensorValue[sonar] < open_distance && time1[T1] < 6000){
			Drive(0, -turn_with_beacon_speed);
			delay(20);
		}
		StopDrive();
		delay(200);

		// push forward; stop if we hit a wall
		bool hit_wall = false;
		clearTimer(T1);
		while(time1[T1] < push_time){
			if(SensorValue[bumper] == 1){
				hit_wall = true;
				break;
			}
			Drive(forward_speed, 0);
			delay(20);
		}
		StopDrive();

		if(!hit_wall) return; // drove the full push time without hitting anything - done

		Drive(-25, 0);
		delay(300);
		Drive(0, -turn_with_beacon_speed);
		delay(800);
		StopDrive();
	}
}

task main(){
	freq = 0;
	ambient_level = 200;
	slow_level = 5000;
	stop_level = 6000;
	expose_time = 5;
	steer_sensitivity = 20;
	forward_speed = 35;
	slow_speed = 25;
	spin_speed = 50;

	// keep the arm up while driving
	motor[armServo] = arm_up_pos;
	delay(arm_move_time);

	// Task 1: go to the red beacon and stop
	GoToBeacon(0);

	// Task 2: turn the red beacon off
	TurnOffRedBeacon();

	// back away from the red beacon before searching for green
	Drive(-40, 0);
	delay(800);
	StopDrive();

	// Task 3: go to the green beacon
	GoToBeacon(1);

	// Task 4: push the green beacon out of the arena
	PushGreenOut();

	StopDrive();
}
