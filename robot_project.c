task main()
{
    int foundRed;
    int redOff;
    int foundGreen;
    int t;

    clearDebugStream();

    // Initialize IRB controls and odometry.
    expose_time = EXPOSURE_TIME_MS;
    freq = RED_BEACON_FREQUENCY;
    SensorValue[digital10] = freq;
    SensorValue[digital11] = 1;
    SensorValue[digital12] = 1;
    wait1Msec(10);
    SensorValue[digital12] = 0;
    SensorValue[digital11] = 0;

    lastRightCommand = 0;
    lastLeftCommand = 0;
    motor[rightMotor] = 0;
    motor[leftMotor] = 0;

    // Start with the claw open and the press arm retracted.
    motor[clawServo] = CLAW_OPEN_POS;
    motor[pressArmServo] = PRESS_ARM_HOME_POS;
    wait1Msec(SERVO_MOVE_TIME_MS);

    if(USE_START_SWITCH)
    {
        // Put the robot down, then press and release the front switch to start.
        writeDebugStreamLine("READY: press and release the front switch");
        while(!LimitSwitchPressed())
            wait1Msec(10);
        while(LimitSwitchPressed())
            wait1Msec(10);
        wait1Msec(START_DELAY_MS);
    }
    else if(LimitSwitchPressed())
    {
        // Avoid starting while the front switch is already held down.
        StopAndHold();
    }

    robotX = 0.0;
    robotY = 0.0;
    robotHeading = 0.0;
    lastOdometryTime = nSysTime;
    runStart = nSysTime;

    // TASK 1: find the red (1 kHz) beacon.
    writeDebugStreamLine("0.0 s  TASK 1: find RED (LED5 on IR board ON)");
    foundRed = SeekBeacon(RED_BEACON_FREQUENCY, RED_SEARCH_TIMEOUT_MS, 1);
    redOff = 0;

    if(foundRed)
    {
        // Remember where the red beacon is, so it is not mistaken for green later.
        UpdateOdometry();
        redSpotX = robotX + ROBOT_FRONT_CM * sin(robotHeading);
        redSpotY = robotY + ROBOT_FRONT_CM * cos(robotHeading);
        redSpotKnown = 1;

        // TASK 2: press the red beacon's top button. Keep going even if it does
        // not verify as off, so Tasks 3 and 4 can still score.
        t = RunTenths();
        writeDebugStreamLine("%d.%d s  TASK 2: press red button", t / 10, t % 10);
        redOff = PressRedUntilOff();

        // Back away from the red beacon and confirm the front switch is released.
        // This avoids dragging the disabled red beacon and prevents a false green hit.
        if(!BackAwayFromRedBeacon())
        {
            writeDebugStreamLine("front switch stuck after backing up: stop");
            StopAndHold();
        }
    }
    else
    {
        writeDebugStreamLine("red not found in time: go on to green");
    }

    // TASK 3: find the green (10 kHz) beacon. Once red is verified off it cannot
    // be mistaken for green, so the slower wrong-beacon check is skipped.
    t = RunTenths();
    writeDebugStreamLine("%d.%d s  TASK 3: find GREEN (LED5 OFF)", t / 10, t % 10);
    foundGreen = SeekBeacon(GREEN_BEACON_FREQUENCY, GREEN_SEARCH_TIMEOUT_MS, !redOff);
    if(!foundGreen)
    {
        writeDebugStreamLine("green not found in time: stop");
        StopAndHold();
    }

    // TASK 4: pin the green beacon by pressing the arm down on top of it, then
    // close the claw around it. The arm stays down while pulling so the beacon
    // cannot slip out. (Pressing down may switch the green beacon off; that is
    // fine, the task is only to move it out of the arena.)
    t = RunTenths();
    writeDebugStreamLine("%d.%d s  TASK 4: grab green, back out", t / 10, t % 10);
    motor[pressArmServo] = PRESS_ARM_HOLD_GREEN_POS;
    wait1Msec(SERVO_MOVE_TIME_MS);

    motor[clawServo] = CLAW_CLOSED_POS;
    wait1Msec(SERVO_MOVE_TIME_MS);

    // From here on the robot pulls the beacon and moves slower.
    UpdateOdometry();
    speedScale = PULL_SPEED_FACTOR;

    // Pull the green beacon backward past the estimated starting point, across
    // the starting line. robotX/Y/Heading have been updated throughout the
    // beacon-search and retreat motions. The return controller uses those
    // estimates; it does not use encoders.
    ReturnToStartBackward();

    // Finished: stop the drive motors and continue holding the green beacon.
    t = RunTenths();
    writeDebugStreamLine("%d.%d s  DONE", t / 10, t % 10);
    StopAndHold();
}
