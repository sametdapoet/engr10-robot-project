/*Test 3: prints switch and sonar values for 20 seconds.
Press each switch and move your hand in front of the sonar to see the numbers change.*/
void TestSwitchesAndSonar(){
	writeDebugStreamLine("TEST 3: SWITCHES + SONAR (20 s)");
	writeDebugStreamLine("  press limit switch -> limit=1, press bumper -> bumper=1");
	writeDebugStreamLine("  hand in front of sonar -> cm should change (-1 = nothing in range)");
	clearTimer(T1);
	while(time1[T1] < 20000){
		writeDebugStreamLine("  limit=%d bumper=%d sonar=%d cm", SensorValue[frontLimit], SensorValue[bumper], SensorValue[sonar]);
		delay(250);
	}
}

/*Test 4: reads all 8 IR detectors at one frequency for 15 seconds.
Point a beacon at the board from different sides - the biggest number should move from PD0 to PD7.*/
void TestIRBoard(int beacon_freq){
	SensorValue[digital10] = beacon_freq; // 0 = 1kHz (red), 1 = 10kHz (green)
	delay(20);
	if(beacon_freq == 0) writeDebugStreamLine("TEST 4: IR BOARD - RED beacon (LED5 on board should be ON)");
	else writeDebugStreamLine("TEST 4: IR BOARD - GREEN beacon (LED5 on board should be OFF)");
	writeDebugStreamLine("  no beacon: sum should be small (under ~200). Beacon close: sum in the thousands.");
	clearTimer(T1);
	while(time1[T1] < 15000){
		ReadPD();
		writeDebugStreamLine("  %d %d %d %d %d %d %d %d  sum=%d", PD0, PD1, PD2, PD3, PD4, PD5, PD6, PD7, PD_sum);
		delay(300);
	}
}

task main(){
	clearDebugStream();
	writeDebugStreamLine("Starting in 3 s - wheels OFF the ground!");
	delay(3000);

	if(TEST == 0 || TEST == 1) TestDrive();
	if(TEST == 0 || TEST == 2) TestArm();
	if(TEST == 0 || TEST == 3) TestSwitchesAndSonar();
	if(TEST == 0 || TEST == 4){
		TestIRBoard(0);
		TestIRBoard(1);
	}

	writeDebugStreamLine("ALL TESTS DONE");
}
